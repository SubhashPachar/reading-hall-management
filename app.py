        flash(
            f"{data['student_name']} assigned to Seat {data['seat_no_int']} "
            f"({OCCUPANCY_LABELS[data['occupancy']]}).", "success",
        )
        return redirect(url_for("library_seat_detail", library_id=library_id, seat_no=data["seat_no_int"]))

