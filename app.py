def admin_count(db=None):
    db = db or get_db()
    return db.execute("SELECT COUNT(*) AS c FROM admins").fetchone()["c"]


def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if "admin_id" not in session:
            return redirect(url_for("login", next=request.path))
        return view(*args, **kwargs)
    return wrapped


@app.route("/setup", methods=["GET", "POST"])
def setup():
    db = get_db()
    if admin_count(db) > 0:
        flash("Setup is already complete. Please log in.", "error")
        return redirect(url_for("login"))

    form_data = {"username": ""}
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        confirm = request.form.get("confirm_password", "")
        form_data["username"] = username

        errors = []
        if not username:
            errors.append("Username is required.")
        if len(password) < 6:
            errors.append("Password must be at least 6 characters.")
        if password != confirm:
            errors.append("Passwords do not match.")

        if errors:
            for e in errors:
                flash(e, "error")
            return render_template("setup.html", form_data=form_data)

        db.execute(
            "INSERT INTO admins (username, password_hash) VALUES (%s, %s)",
            (username, generate_password_hash(password)),
        )
        db.commit()
        flash("Admin account created. Please log in.", "success")
        return redirect(url_for("login"))

    return render_template("setup.html", form_data=form_data)


@app.route("/login", methods=["GET", "POST"])
def login():
    db = get_db()
    if admin_count(db) == 0:
        return redirect(url_for("setup"))
    if "admin_id" in session:
        return redirect(url_for("libraries_list"))

    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        admin = db.execute(
            "SELECT * FROM admins WHERE username = %s", (username,)
        ).fetchone()

        if admin and check_password_hash(admin["password_hash"], password):
            session.clear()
            session["admin_id"] = admin["id"]
            session["admin_username"] = admin["username"]
            flash(f"Welcome back, {admin['username']}.", "success")
            next_url = request.args.get("next") or url_for("libraries_list")
            return redirect(next_url)

        flash("Invalid username or password.", "error")

    return render_template("login.html")


